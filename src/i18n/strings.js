// If lang is Hindi and a "<field>_hi" value exists, it replaces the English "<field>"
export function localize(obj, lang) {
  if (lang !== 'hi' || !obj) return obj
  const out = { ...obj }
  for (const k of Object.keys(obj)) {
    if (k.endsWith('_hi') && obj[k]) out[k.slice(0, -3)] = obj[k]
  }
  return out
}